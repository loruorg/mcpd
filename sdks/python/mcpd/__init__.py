"""mcpd: agent observability for Python.

    from mcpd import Mcpd

    mcpd = Mcpd()                       # reads MCPD_* from the environment
    with mcpd.trace("support_agent") as run:
        run.set_input({"question": "where is my order?"})
        with mcpd.span("answer", kind="model_generation") as gen:
            gen.set_model("gpt-4o-mini", "openai")
            gen.set_usage(input_tokens=812, output_tokens=96)
    mcpd.shutdown()

Recording never blocks and never raises. Reads do raise, because a query that
quietly returned nothing would be the worse bug.

The generated wire types live in `mcpd.records`. One of them, the stored `Span`
record, shares its name with the live `Span` handle this package exports, so it
is also re-exported here as `SpanRecord`.
"""


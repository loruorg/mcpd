import { parseType, pascal, snake, comment, banner, allObjects, defaultLiteral } from './lib.mjs'

const MAP = { string:'String', bool:'bool', f64:'f64', u64:'u64', u32:'u32', i64:'i64',
  json:'serde_json::Value', timestamp:'time::OffsetDateTime' }

function ty(t) {
  const { base, array, optional } = parseType(t)
  let r = MAP[base] ?? pascal(base)
  if (array) r = `Vec<${r}>`
  if (optional) r = `Option<${r}>`
  return r
}

export function emitRust(spec) {
  // `banner()` already ends in a newline, so no separator element belongs here:
  // an empty string would emit a second blank line, which rustfmt then collapses
  // and the format check reports as drift on every run.
  const o = [banner('// '),
    '//! The mcpd data model, generated from `spec/mcpd.spec.json`.',
    '//!',
    '//! Every type here is the same shape the HTTP API speaks and the other five',
    '//! SDKs mirror. Do not edit this file: change the spec and run `make gen`.',
    '',
    '#![allow(clippy::all)]',
    'use serde::{Deserialize, Serialize};', '']

  o.push('/// The version of `spec/mcpd.spec.json` these types were generated from.')
  o.push('///')
  o.push('/// A daemon reports the same string as `spec_version` on `/healthz`. Compare the')
  o.push('/// two at connect time. A mismatch caught there names the problem; the same')
  o.push('/// mismatch found later shows up as a field missing for no visible reason.')
  o.push(`pub const SPEC_VERSION: &str = "${spec.specVersion}";`)
  o.push('')

  for (const [name, e] of Object.entries(spec.enums)) {
    o.push(comment(e.doc, '/// '))
    o.push('#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]')
    o.push('#[serde(rename_all = "snake_case")]')
    o.push(`pub enum ${pascal(name)} {`)
    for (const v of e.values) {
      o.push(comment(v.doc, '/// ', '    '))
      o.push(`    ${pascal(v.name)},`)
    }
    o.push('}', '')
    o.push(`impl ${pascal(name)} {`)
    o.push('    /// The wire representation, exactly as it appears in JSON.')
    o.push('    pub const fn as_str(&self) -> &\'static str {')
    o.push('        match self {')
    for (const v of e.values) o.push(`            Self::${pascal(v.name)} => "${v.name}",`)
    o.push('        }', '    }', '')
    o.push('    /// Every variant, in declaration order.')
    // rustfmt breaks this list one variant per line once it passes 100 columns,
    // and `make check` runs both the drift gate and a format check. Emitting the
    // form rustfmt already agrees with is what stops the two fighting.
    const all = e.values.map((v) => `Self::${pascal(v.name)}`)
    // rustfmt's three forms, in the order it tries them: all on one line; the
    // whole array moved to the next line; then one variant per line.
    const oneLine = `    pub const ALL: &'static [Self] = &[${all.join(', ')}];`
    const wrapped = `        &[${all.join(', ')}];`
    if (oneLine.length <= 100) {
      o.push(oneLine)
    } else if (wrapped.length <= 100) {
      o.push(`    pub const ALL: &'static [Self] =`)
      o.push(wrapped)
    } else {
      o.push(`    pub const ALL: &'static [Self] = &[`)
      for (const v of all) o.push(`        ${v},`)
      o.push('    ];')
    }
    if (e.values.every(v => 'severity' in v)) {
      o.push('', '    /// Ordered severity. Filtering is always `>=`.')
      o.push('    pub const fn severity(&self) -> u8 {')
      o.push('        match self {')
      for (const v of e.values) o.push(`            Self::${pascal(v.name)} => ${v.severity},`)
      o.push('        }', '    }')
    }
    o.push('}', '')
    o.push(`impl std::str::FromStr for ${pascal(name)} {`)
    o.push('    type Err = ();')
    o.push('    fn from_str(s: &str) -> Result<Self, ()> {')
    o.push('        match s {')
    for (const v of e.values) o.push(`            "${v.name}" => Ok(Self::${pascal(v.name)}),`)
    o.push('            _ => Err(()),', '        }', '    }', '}', '')
    o.push(`impl std::fmt::Display for ${pascal(name)} {`)
    o.push('    fn fmt(&self, f: &mut std::fmt::Formatter<\'_>) -> std::fmt::Result {')
    o.push('        f.write_str(self.as_str())')
    o.push('    }')
    o.push('}', '')
  }

  for (const { name, def } of allObjects(spec)) {
    o.push(comment(def.doc, '/// '))
    if (def.table) o.push(`/// Stored in the \`${def.table}\` table.`)
    o.push('#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]')
    o.push(`pub struct ${pascal(name)} {`)
    const defaulted = def.fields.filter(f => f.default !== undefined)
    for (const f of def.fields) {
      o.push(comment(f.doc, '/// ', '    '))
      const { optional, array, base } = parseType(f.type)
      if (f.default !== undefined) {
        o.push(`    #[serde(default = "${snake(name)}_default_${snake(f.name)}")]`)
      } else if (optional) {
        o.push('    #[serde(default, skip_serializing_if = "Option::is_none")]')
      } else if (array) {
        o.push('    #[serde(default)]')
      }
      if (base === 'timestamp') o.push('    #[serde(with = "time::serde::rfc3339' + (optional ? '::option' : '') + '")]')
      o.push(`    pub ${snake(f.name)}: ${ty(f.type)},`)
    }
    o.push('}', '')
    for (const f of defaulted) {
      o.push(`/// Spec-declared default for [\`${pascal(name)}::${snake(f.name)}\`].`)
      // rustfmt puts a function body on its own line whatever its length, so
      // the one-line form would be rewritten on the next format run.
      o.push(`fn ${snake(name)}_default_${snake(f.name)}() -> ${ty(f.type)} {`)
      o.push(`    ${defaultLiteral('rust', f.type, f.default)}`)
      o.push('}', '')
    }
    // A struct every field of which can be defaulted gets a Default impl, so
    // callers can build one with `..Default::default()`.
    const defaultable = def.fields.every(f => {
      const p = parseType(f.type)
      return p.optional || p.array || f.default !== undefined
    })
    if (defaultable) {
      const inits = def.fields.map((f) => {
        const p = parseType(f.type)
        const v = f.default !== undefined
          ? `${snake(name)}_default_${snake(f.name)}()`
          : p.optional ? 'None' : 'Vec::new()'
        return `${snake(f.name)}: ${v}`
      })
      o.push(`impl Default for ${pascal(name)} {`)
      o.push('    fn default() -> Self {')
      // `use_small_heuristics = "Max"` keeps a struct literal on one line while
      // it fits, so emit that form rather than leaving rustfmt to rewrite it.
      const flat = `        Self { ${inits.join(', ')} }`
      if (flat.length <= 100) {
        o.push(flat)
      } else {
        o.push('        Self {')
        for (const i of inits) o.push(`            ${i},`)
        o.push('        }')
      }
      o.push('    }', '}', '')
    }
    if (def.primaryKey) {
      o.push(`impl ${pascal(name)} {`)
      o.push('    /// The primary key, as declared in the spec.')
      o.push(`    pub const PRIMARY_KEY: &'static [&'static str] = &[${def.primaryKey.map(k => `"${snake(k)}"`).join(', ')}];`)
      o.push(`    /// The storage table this entity lives in.`)
      o.push(`    pub const TABLE: &'static str = "${def.table}";`)
      o.push('}', '')
    }
  }
  return o.join('\n')
}
